# tests/workflows.py — browser end-to-end workflows for all three roles + accessibility scan.
# Run with the server started (npm start) on a FRESH demo database:  python3 tests/workflows.py
import asyncio, json, sys, pathlib
from playwright.async_api import async_playwright, expect
BASE = 'http://localhost:3000/'
AXE = pathlib.Path(__file__).resolve().parent.parent.joinpath('node_modules/axe-core/axe.min.js').read_text()
results, errors = [], []
def ok(name): results.append(('PASS', name)); print('PASS', name)
async def login(pg, email):
    await pg.goto(BASE + '#/login'); await pg.wait_for_selector('#loginForm')
    await pg.fill('#loginForm input[name=email]', email); await pg.fill('#loginForm input[name=password]', 'Password123!')
    await pg.click('#loginForm [type=submit]'); await pg.wait_for_function("location.hash.startsWith('#/dashboard') || location.hash.startsWith('#/admin')")
async def logout(pg):
    await pg.evaluate("fetch('/api/auth/logout',{method:'POST'})"); await pg.goto(BASE + '#/'); await pg.reload(); await pg.wait_for_timeout(400)
async def axe(pg, label):
    await pg.add_script_tag(content=AXE)
    r = await pg.evaluate("axe.run(document, {runOnly: {type: 'tag', values: ['wcag2a','wcag2aa','wcag21a','wcag21aa','wcag22aa']}}).then(r => r.violations.map(v => ({id: v.id, impact: v.impact, n: v.nodes.length, ex: v.nodes[0].target.join(' ')})))")
    if r: errors.append(f'AXE {label}: {json.dumps(r)}')
    else: ok(f'axe: no WCAG A/AA violations on {label}')

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        pg = await (await b.new_context(viewport={'width': 1280, 'height': 900}, bypass_csp=True)).new_page()
        pg.on('pageerror', lambda e: errors.append('PAGEERROR ' + str(e)))
        pg.on('console', lambda m: errors.append('CONSOLE ' + m.text) if m.type == 'error' else None)
        pg.on('dialog', lambda d: asyncio.ensure_future(d.dismiss()))

        # ---- Public pages + accessibility ----
        for h, label in [('#/', 'home'), ('#/explore', 'explore'), ('#/mentor/3', 'public mentor profile'), ('#/login', 'login'), ('#/register', 'register'), ('#/about', 'about'), ('#/safety', 'safety center')]:
            await pg.goto(BASE + h); await pg.wait_for_timeout(700); await axe(pg, label)
        await pg.goto(BASE + '#/explore?industry=Healthcare'); await pg.wait_for_timeout(700)
        assert 'Priya' in await pg.inner_text('#dirResults') and 'Marcus' not in await pg.inner_text('#dirResults'); ok('industry link filters the public directory')
        await pg.goto(BASE + '#/'); await pg.wait_for_timeout(500)
        await pg.reload(); await pg.wait_for_timeout(500); await pg.keyboard.press('Tab'); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(200)
        assert await pg.evaluate("location.hash") == '#/' and await pg.evaluate("document.activeElement.id") == 'main'; ok('skip link moves focus to main without breaking the route')

        # ---- Registration: guided student onboarding with field errors ----
        await pg.goto(BASE + '#/register'); await pg.wait_for_selector('#regForm')
        await pg.click('#nextBtn'); await pg.wait_for_timeout(200)
        assert 'full name' in (await pg.inner_text('[data-field=name] .field-error')).lower(); ok('registration shows the error next to the field')
        await pg.fill('#regForm input[name=name]', 'Riley Test'); await pg.fill('#regForm input[name=email]', 'riley@example.com'); await pg.fill('#regForm input[name=password]', 'Password123!')
        await pg.click('#nextBtn'); await pg.select_option('#regForm select[name=grade_level]', '10th grade')
        await pg.fill('#regForm [data-taginput=interests] .tag-input input', 'computer science'); await pg.keyboard.press('Enter')
        await pg.click('#nextBtn'); await pg.fill('#regForm textarea[name=career_goals]', 'Learn about software internships and engineering careers.')
        await pg.check('#regForm input[name=agree]'); await pg.click('#nextBtn'); await pg.wait_for_timeout(300)
        assert 'parent or guardian' in (await pg.inner_text('[data-field=guardianAck] .field-error')); ok('high school students must confirm guardian awareness')
        await pg.check('#regForm input[name=guardianAck]'); await pg.click('#nextBtn')
        await pg.wait_for_function("location.hash.startsWith('#/dashboard')"); await pg.wait_for_timeout(600)
        assert 'Find your first mentor' in await pg.inner_text('#main'); ok('new student lands on a first-step dashboard')
        await axe(pg, 'new student dashboard')
        await logout(pg)

        # ---- Mentor application → pending → admin approves ----
        await pg.goto(BASE + '#/register?role=mentor'); await pg.wait_for_selector('#regForm')
        await pg.fill('#regForm input[name=name]', 'Jordan Mentor'); await pg.fill('#regForm input[name=email]', 'jordan@example.com'); await pg.fill('#regForm input[name=password]', 'Password123!')
        await pg.click('#nextBtn'); await pg.fill('#regForm input[name=headline]', 'UX Designer'); await pg.select_option('#regForm select[name=industry]', 'Arts & Media')
        await pg.click('#nextBtn'); await pg.fill('#regForm [data-taginput=interests] .tag-input input', 'design portfolios'); await pg.keyboard.press('Enter')
        await pg.click('#nextBtn'); await pg.check('#regForm input[name=agree]'); await pg.click('#nextBtn')
        await pg.wait_for_function("location.hash.startsWith('#/dashboard')"); await pg.wait_for_timeout(600)
        assert 'being reviewed' in await pg.inner_text('#main'); ok('new mentor sees the pending-approval notice')
        await logout(pg)
        await pg.goto(BASE + '#/explore'); await pg.wait_for_timeout(600)
        assert 'Jordan Mentor' not in await pg.inner_text('#main'); ok('pending mentor is hidden from the directory')

        # ---- Student journey: discover → profile → book (calendar) → chat → report ----
        await login(pg, 'sam@example.com'); await pg.wait_for_timeout(500)
        assert 'Recommended for you' in await pg.inner_text('#main'); ok('student dashboard shows next appointment and recommendations')
        await pg.goto(BASE + '#/mentors'); await pg.wait_for_timeout(800)
        await pg.fill('#dirQ', 'law'); await pg.wait_for_timeout(800)
        assert 'Aisha Khan' in await pg.inner_text('#dirResults'); ok('directory search works')
        assert 'law' in await pg.evaluate('location.hash'); ok('filters are kept in the URL')
        await pg.click('[data-remove-filter=q]'); await pg.wait_for_timeout(600)
        await pg.click('#dirResults [data-action=save] >> nth=0'); await pg.wait_for_timeout(400)
        await pg.goto(BASE + '#/my-mentors?tab=saved'); await pg.wait_for_timeout(600)
        assert 'Saved' in await pg.inner_text('#main') and await pg.locator('#main .mentor-card').count() >= 1; ok('saved mentors appear under My mentors')
        await pg.goto(BASE + '#/users/5'); await pg.wait_for_timeout(600)   # James (not connected)
        await pg.click('[data-action=request]'); await pg.fill('#dialog textarea[name=message]', 'Hi James! I would love advice on getting into engineering programs.')
        await pg.click('#dialog [type=submit]'); await pg.wait_for_timeout(700)
        assert 'Awaiting response' in await pg.inner_text('#main'); ok('requesting mentorship updates the profile action to Awaiting response')
        await pg.goto(BASE + '#/users/3'); await pg.wait_for_timeout(600)
        await pg.click('text=Book a session with Marcus'); await pg.wait_for_selector('#cal .has-slots')
        await pg.check('#bookForm input[name=duration][value="45"]'); await pg.wait_for_timeout(600)
        await pg.click('#cal .has-slots >> nth=1'); await pg.click('#slots [data-time] >> nth=0')
        await pg.fill('#bookForm input[name=topic]', 'Reviewing my robotics project')
        await axe(pg, 'booking')
        await pg.click('#summary [type=submit]'); await pg.wait_for_selector('text=Session requested')
        ok('student booked a 45-minute session from real availability')
        await pg.goto(BASE + '#/sessions?tab=awaiting'); await pg.wait_for_timeout(600)
        assert 'Reviewing my robotics project' in await pg.inner_text('#main'); ok('booked session shows as Awaiting confirmation')
        await pg.goto(BASE + '#/sessions/2'); await pg.wait_for_selector('#msg')
        await pg.fill('#msg', 'Hi Marcus! Looking forward to our chat.'); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(700)
        assert 'Looking forward' in await pg.inner_text('#chatLog'); ok('chat message sent and appended')
        await axe(pg, 'chat')
        await logout(pg)

        # ---- Mentor: confirm the request, accept/decline, reply in chat, report message ----
        await login(pg, 'marcus@example.com'); await pg.wait_for_timeout(600)
        await axe(pg, 'mentor dashboard')
        await pg.click('#main [data-action=session-confirm] >> nth=0'); await pg.wait_for_timeout(800)
        ok('mentor confirmed the booked session from the dashboard')
        await pg.goto(BASE + '#/sessions/2'); await pg.wait_for_selector('#msg')
        await pg.fill('#msg', 'Great to meet you, Sam. What should we focus on?'); await pg.click('#composer [type=submit]'); await pg.wait_for_timeout(600)
        await pg.click('#chatLog [data-action=report] >> nth=0'); await pg.check('#dialog input[value="Spam or fake profile"]'); await pg.click('#dialog [type=submit]'); await pg.wait_for_timeout(600)
        assert 'Report submitted' in await pg.inner_text('#dialog'); ok('mentor reported a chat message')
        await pg.keyboard.press('Escape')
        await pg.goto(BASE + '#/availability'); await pg.wait_for_selector('#availForm')
        await pg.click('[data-add-win="5"]'); await pg.click('#availForm [type=submit]'); await pg.wait_for_timeout(600)
        assert 'Saved' in await pg.inner_text('#availNote'); ok('mentor added a Friday availability window')
        await axe(pg, 'availability')
        await pg.goto(BASE + '#/profile'); await pg.wait_for_selector('#profileForm')
        await axe(pg, 'mentor profile editor')
        await logout(pg)

        await login(pg, 'james@example.com'); await pg.goto(BASE + '#/requests'); await pg.wait_for_timeout(600)
        await axe(pg, 'mentor requests')
        await pg.click('[data-req-accept]'); await pg.wait_for_timeout(800)
        assert 'You accepted Sam Lee' in await pg.inner_text('#main'); ok('accepting a request explains the next step')
        await logout(pg)

        # ---- Admin: approve mentor, review report with context, audit log ----
        await login(pg, 'admin@mentorshipmatch.org'); await pg.wait_for_timeout(600)
        await axe(pg, 'admin overview')
        await pg.goto(BASE + '#/admin/approvals'); await pg.wait_for_timeout(600)
        await pg.click('[data-approve=approved][data-name="Jordan Mentor"]'); await pg.click('#dialog [type=submit]'); await pg.wait_for_timeout(700)
        ok('admin approved the new mentor')
        await pg.goto(BASE + '#/admin/reports'); await pg.wait_for_timeout(600)
        await axe(pg, 'moderation queue')
        await pg.click('#main a:has-text("Details") >> nth=0'); await pg.wait_for_timeout(700)
        assert 'Great to meet you' in await pg.inner_text('#main'); ok('report case view shows the conversation context')
        await axe(pg, 'report case view')
        await pg.click('[data-flag-act=hide_content]'); await pg.click('#dialog [type=submit]'); await pg.wait_for_timeout(300)
        assert 'reason' in (await pg.inner_text('#dialog')).lower(); ok('removing content requires a reason')
        await pg.fill('#dialog textarea[name=note]', 'Message was not spam; test removal.'); await pg.click('#dialog [type=submit]'); await pg.wait_for_timeout(700)
        await pg.goto(BASE + '#/admin/audit'); await pg.wait_for_timeout(600)
        assert 'test removal' in await pg.inner_text('#main'); ok('audit log records who, what, and why')
        await pg.goto(BASE + '#/admin/users/9'); await pg.wait_for_timeout(600); await axe(pg, 'admin user detail')
        await logout(pg)
        await pg.goto(BASE + '#/explore'); await pg.wait_for_timeout(700)
        assert 'Jordan Mentor' in await pg.inner_text('#main'); ok('approved mentor now appears publicly')

        # ---- Settings: theme, language, font; mobile layout ----
        await pg.goto(BASE + '#/'); await pg.wait_for_timeout(500)
        await pg.click('[data-open-settings] >> nth=0'); await pg.wait_for_selector('#settingsForm')
        await axe(pg, 'settings panel')
        await pg.check('#settingsForm input[value=dark]'); await pg.select_option('#langSel', 'es'); await pg.wait_for_timeout(500)
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(300)
        assert await pg.evaluate("document.documentElement.dataset.theme") == 'dark'; assert 'conversación' in await pg.inner_text('#main')
        assert await pg.evaluate("document.querySelector('#main').lang") == 'es'; ok('dark theme + Spanish applied, translated region marked lang=es')
        await axe(pg, 'home in dark theme (Spanish)')
        await pg.evaluate("MMPrefs.reset()")
        m = await (await b.new_context(viewport={'width': 390, 'height': 844})).new_page()
        await m.goto(BASE + '#/'); await m.wait_for_timeout(600)
        overflow = await m.evaluate("document.documentElement.scrollWidth > window.innerWidth + 1")
        assert not overflow; ok('mobile 390px: no horizontal scrolling on home')
        await m.screenshot(path='/tmp/v3_mobile_home.png')
        await m.click('[data-open-nav]'); await m.wait_for_timeout(300); await m.screenshot(path='/tmp/v3_mobile_nav.png')
        w320 = await (await b.new_context(viewport={'width': 320, 'height': 700})).new_page()
        for h in ['#/', '#/explore', '#/login', '#/register', '#/safety']:
            await w320.goto(BASE + h); await w320.wait_for_timeout(500)
            if await w320.evaluate("document.documentElement.scrollWidth > window.innerWidth + 1"): errors.append(f'REFLOW 320px overflow on {h}')
        ok('320px reflow checked on public pages')
        await b.close()
    print(f"\n{len(results)} checks passed, {len(errors)} problems")
    for e in errors: print('PROBLEM', e[:600])
    sys.exit(1 if errors else 0)
asyncio.run(main())
